const esbuild = require('esbuild');
const fs = require('fs');
const { execFileSync } = require('child_process');
process.chdir(__dirname); // allow running from any cwd (e.g. Playwright webServer)

const outfile = 'dist/index.js';

esbuild.build({
  entryPoints: ['src/index.ts'],
  absWorkingDir: __dirname,
  bundle: true,
  minify: true,
  outfile,
  platform: 'node',
  format: 'cjs',
  target: ['node18'],
  external: ['devsense-php-ls', 'ws'],
}).then(() => {
  fs.chmodSync(outfile, '755'); // make executable (bin)
  console.log(`✅ Built CJS bundle: ${outfile}`);
  // Browser-safe ESM bundle of the Monaco LSP providers (src/providers/browser-index.ts).
  // This is the single source for sampleweb (`import ... from 'devsense-php-editor/browser'`).
  return esbuild.build({
    entryPoints: ['src/providers/browser-index.ts'],
    absWorkingDir: __dirname,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: ['es2020'],
    outfile: 'dist-browser/providers.browser.js',
    // monaco-editor stays a bare import so the consumer's bundler resolves it once
    // (including its CSS and its `new URL(..., import.meta.url)` workers).
    external: ['monaco-editor', 'monaco-editor/*'],
    banner: { js: '// GENERATED by build.js from src/providers + src/browser — do not edit.' },
  }).then(() => {
    console.log('✅ Built browser bundle: dist-browser/providers.browser.js');
    // Type declarations for both entry points (dist/types/**/*.d.ts).
    execFileSync(process.execPath, [require.resolve('typescript/bin/tsc'), '-p', 'tsconfig.types.json'], { stdio: 'inherit' });
    console.log('✅ Emitted type declarations: dist/types');
  });
}).catch((err) => {
  console.error('❌ Build failed:', err);
  process.exit(1);
});
